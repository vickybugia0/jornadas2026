<section class="project-content">
    <h2>Materias Integradas y Ejes de Trabajo</h2>
    <div class="subject-grid">
        
        <div class="subject-card">
            <h3>🧪 Química / Ciudadanía y Participación</h3>
            <p>
                Análisis del impacto ambiental de las baterías de celular. Experimentación y explicación de 
                cambios químicos (gases, color, precipitados) y cómo estos contaminan el entorno cotidiano.
            </p>
        </div>

        <div class="subject-card">
            <h3>📚 Lengua y Literatura / Artes Visuales</h3>
            <p>
                Análisis de publicidades tecnológicas (lo dicho y lo no dicho). Transformación del lenguaje técnico 
                en imágenes lingüísticas y reflexivas, además de producciones visuales para visibilizar la problemática.
            </p>
        </div>

        <div class="subject-card">
            <h3>⏳ Historia / Educación Tecnológica e Informática</h3>
            <p>
                Estudio de la evolución de los celulares en la 3ra y 4ta revolución industrial. Charlas con 
                "ciber cirujas", recuperación de partes (cámaras) y análisis del ciclo de vida de la tecnología.
            </p>
        </div>

        <div class="subject-card">
            <h3>📊 Matemática</h3>
            <p>
                Recolección de datos a través de encuestas institucionales y análisis estadístico del "stock" 
                de residuos electrónicos (RAEE) acumulados en los hogares.
            </p>
        </div>

    </div>
</section>

