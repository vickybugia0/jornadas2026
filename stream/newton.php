<section class="project-content">
    <h2>¿En qué consiste?</h2>
    <p>
        El proyecto busca cuantificar el "stock" de residuos electrónicos en las familias del Instituto, 
        analizar críticamente la obsolescencia programada y ejercer una ciudadanía activa mediante campañas 
        de gestión de residuos. Se recuperan celulares en desuso, se aprende a "limpiarlos" de datos personales 
        para donarlos o reciclarlos, y se investiga el impacto ambiental de sus componentes químicos.
    </p>
</section>

