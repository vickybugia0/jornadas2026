        From the English area, the same problem regarding biodiversity loss and ecological disasters is 
        approached from a global perspective, covering countries like Australia, Spain, and Sri Lanka. 
        Students utilize specific vocabulary including extreme adjectives and natural disasters from 
        Gateway to the World B1+ (Unit 3).
    </div>
</section>

