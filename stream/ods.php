<section class="project-content">
    <h2>¿En qué consiste?</h2>
    <p>
        Los estudiantes investigan la pérdida y conservación de la biodiversidad bajo el marco de la 
        economía circular, analizando desde las prácticas de las sociedades precolombinas hasta las 
        problemáticas ambientales actuales. El proyecto se divide en comisiones de trabajo enfocadas en 
        distintos ODS y una dedicada exclusivamente a la concientización general (Raise Awareness).
    </p>
</section>

<section class="project-content">
    <div class="quote-box" style="font-size: 22px; font-style: normal; text-align: left; line-height: 1.6;">
